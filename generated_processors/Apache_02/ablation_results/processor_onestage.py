import sys
from datetime import datetime, timedelta
from typing import List, Dict, Tuple, Any

class EventProcessor:
    """
    Groups raw Apache HTTP Server logs into logical security events based on
    temporal and contextual heuristics.
    """

    def __init__(self, logs: List[Dict[str, Any]]):
        """
        Initializes the EventProcessor with a list of log entries.

        Args:
            logs: A list of dictionaries, where each dictionary represents a log entry.
        """
        self.original_logs = logs
        self.processed_logs: List[Dict[str, Any]] = []

        # Pre-process logs: parse timestamps and store original indices
        for i, log in enumerate(self.original_logs):
            log_copy = log.copy()
            log_copy['_original_index'] = i
            try:
                # The timestamp format is consistent: 'YYYY-MM-DD HH:MM:SS'
                log_copy['_datetime'] = datetime.strptime(log['Timestamp'], '%Y-%m-%d %H:%M:%S')
                self.processed_logs.append(log_copy)
            except (ValueError, TypeError):
                # Skip logs with invalid or missing timestamps
                continue
        
        # Sort logs chronologically for the single-pass clustering algorithm
        self.processed_logs.sort(key=lambda x: x['_datetime'])

        # Initialize Union-Find (Disjoint Set Union) data structure
        # Each log starts in its own set.
        self.parent = list(range(len(self.processed_logs)))

    def _find(self, i: int) -> int:
        """
        Finds the representative (root) of the set containing element i with path compression.
        """
        if self.parent[i] == i:
            return i
        self.parent[i] = self._find(self.parent[i])
        return self.parent[i]

    def _union(self, i: int, j: int):
        """
        Merges the sets containing elements i and j.
        """
        root_i = self._find(i)
        root_j = self._find(j)
        if root_i != root_j:
            self.parent[root_j] = root_i

    def cluster_events(self) -> Tuple[List[List[int]], Dict[int, int]]:
        """
        Clusters logs into logical security events using a single-pass algorithm.

        The clustering logic uses a combination of heuristics:
        1.  **IP-based Correlation**: Groups logs from the same source IP address that
            occur within a defined time window (session). This is the primary method
            for tracking external user/attacker activity.
        2.  **PID-based Correlation**: Groups logs generated by the same Process ID
            within a time window. This is effective for tracking the lifecycle of a
            single Apache worker process.
        3.  **Internal Event Correlation**: Groups logs that lack an IP address (internal
            system events) if they occur in close temporal succession. This helps
            reconstruct system-level sequences like restarts or module initializations.

        A Union-Find data structure is used to efficiently merge these groups as new
        correlations are found.

        Returns:
            A tuple containing:
            - security_events (List[List[int]]): A list of events, where each event
              is a list of original log indices.
            - log_index_to_event_id (Dict[int, int]): A mapping from a log's original
              index to its assigned event ID.
        """
        # --- Hyperparameters for clustering heuristics ---
        # Time window to correlate events from the same IP (e.g., a user session)
        IP_SESSION_TIMEOUT = timedelta(minutes=5)
        # Time window to correlate events from the same Process ID
        PID_SESSION_TIMEOUT = timedelta(minutes=1)
        # Time window for sequential internal (non-IP) system events
        INTERNAL_EVENT_TIMEOUT = timedelta(seconds=60)

        # --- State tracking for the single-pass algorithm ---
        # Maps an IP address to the index of the last log seen from that IP
        ip_to_last_log_idx: Dict[str, int] = {}
        # Maps a Process ID to the index of the last log seen from that PID
        pid_to_last_log_idx: Dict[str, int] = {}
        # Index of the last seen internal log (one without an IP)
        last_internal_log_idx: int = -1

        # --- Main Clustering Loop ---
        for i, current_log in enumerate(self.processed_logs):
            current_time = current_log['_datetime']
            current_ip = current_log.get('ip')
            current_pid = current_log.get('PID')

            # 1. IP-based correlation (for external events)
            if current_ip:
                if current_ip in ip_to_last_log_idx:
                    last_idx = ip_to_last_log_idx[current_ip]
                    last_time = self.processed_logs[last_idx]['_datetime']
                    if current_time - last_time <= IP_SESSION_TIMEOUT:
                        self._union(i, last_idx)
                # Update the last seen log for this IP
                ip_to_last_log_idx[current_ip] = i

            # 2. PID-based correlation (for process-specific events)
            if current_pid:
                if current_pid in pid_to_last_log_idx:
                    last_idx = pid_to_last_log_idx[current_pid]
                    last_time = self.processed_logs[last_idx]['_datetime']
                    if current_time - last_time <= PID_SESSION_TIMEOUT:
                        self._union(i, last_idx)
                # Update the last seen log for this PID
                pid_to_last_log_idx[current_pid] = i
            
            # 3. Internal event correlation (for sequential system events)
            if not current_ip:
                if last_internal_log_idx != -1:
                    last_log = self.processed_logs[last_internal_log_idx]
                    # Only group with the previous internal log if it's close in time
                    if current_time - last_log['_datetime'] <= INTERNAL_EVENT_TIMEOUT:
                        self._union(i, last_internal_log_idx)
                # This log is now the most recent internal event
                last_internal_log_idx = i

        # --- Post-processing: Build final output structures ---
        # Group logs by their set representative (root)
        clusters: Dict[int, List[int]] = {}
        for i in range(len(self.processed_logs)):
            # Use the original index for the final output
            original_index = self.processed_logs[i]['_original_index']
            root = self._find(i)
            if root not in clusters:
                clusters[root] = []
            clusters[root].append(original_index)

        # Convert clusters map to the required list of lists format
        security_events: List[List[int]] = list(clusters.values())
        
        # Create the mapping from original log index to the new event ID
        log_index_to_event_id: Dict[int, int] = {}
        for event_id, event_logs in enumerate(security_events):
            # Sort logs within each event by their original index for consistency
            event_logs.sort()
            for log_idx in event_logs:
                log_index_to_event_id[log_idx] = event_id

        return security_events, log_index_to_event_id